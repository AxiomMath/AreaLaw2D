#!/usr/bin/env python3
"""List every declaration of AreaLaw/ and AreaLawForMathlib/ and write the index into Map.md.

Declaration rule (as in RefactoringResult §1): a line regex on the keywords def, theorem, lemma,
abbrev, instance, structure, inductive, class at column 0, after attributes and modifiers,
comments stripped. Names are qualified by the enclosing `namespace`s.

Anchor of an AreaLaw/ declaration: the `D*.n[.k]` at the start of its own docstring; else that of
the nearest preceding declaration with one in the same file; else the section heading
(`/-! ## ...`) in force, else the module title.
AreaLawForMathlib/ files record the Mathlib file named after `Extends` in the module docstring.

Usage: scripts/decl_index.py [--write]   (--write replaces the index section at the end of Map.md)
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEAD = "## Declaration index (generated by scripts/decl_index.py)"
KW = r"(?:def|theorem|lemma|abbrev|instance|structure|inductive|class(?:\s+inductive)?)"
DECL = re.compile(r"^(?:@\[[^\]]*\]\s*)*(?:(?:private|protected|noncomputable|unsafe|partial|nonrec|public|meta)\s+)*(" + KW + r")\b\s*(.*)")
ANCH = re.compile(r"^(D\d+\.\d+(?:\.\d+)?)\b")
NAME = re.compile(r"^(?:\{[^}]*\}\s*)?([^\s:({\[⦃]+)")


def extends(text):
    """The `Extends ...` clause of a module docstring, up to its first sentence end."""
    m = re.search(r"Extends\s+((?:[^.:`]|`[^`]*`|\.(?=\w))*)", text)
    if not m: return None
    return re.sub(r"\s+", " ", m.group(1)).strip().rstrip(",;")[:200] or None


def decls(path, rel):
    lines = path.read_text().split("\n")
    out, ns, stack = [], [], []
    in_block, depth = False, 0
    doc, title, section, last_anchor = None, None, None, None
    mathlib = None
    i = 0
    while i < len(lines):
        ln = lines[i]
        s = ln.strip()
        if in_block:
            doc.append(ln)
            depth += ln.count("/-") - ln.count("-/")
            if depth <= 0:
                in_block = False
                text = "\n".join(doc)
                if kind_block == "!":
                    m = re.search(r"^(?:/-!\s*)?#\s+(.*?)(?:\s*-/)?$", text, re.M)
                    if m and title is None: title = m.group(1).strip()
                    mathlib = mathlib or extends(text)
                    for m in re.finditer(r"^(?:/-!\s*)?##+\s+(.*?)(?:\s*-/)?$", text, re.M):
                        section = m.group(1).strip()
                    doc = None
                else:
                    pending = text
                    doc = None
                    cur_doc[0] = pending
            i += 1
            continue
        if ln.startswith("/-"):
            kind_block = "!" if ln.startswith("/-!") else ("-" if ln.startswith("/--") else "c")
            if kind_block == "c":
                # plain comment: skip
                d = ln.count("/-") - ln.count("-/")
                j = i
                while d > 0:
                    j += 1; d += lines[j].count("/-") - lines[j].count("-/")
                i = j + 1
                continue
            doc = [ln]
            depth = ln.count("/-") - ln.count("-/")
            if depth <= 0:
                text = ln
                if kind_block == "!":
                    m = re.search(r"^(?:/-!\s*)?#\s+(.*?)(?:\s*-/)?$", text, re.M)
                    if m and title is None: title = m.group(1).strip()
                    m = re.search(r"^(?:/-!\s*)?##+\s+(.*?)(?:\s*-/)?$", text, re.M)
                    if m: section = m.group(1).strip()
                    mathlib = mathlib or extends(text)
                else:
                    cur_doc[0] = text
                doc = None
            else:
                in_block = True
            i += 1
            continue
        m = re.match(r"^namespace\s+(\S+)", ln)
        if m:
            stack.append(m.group(1)); ns.extend(m.group(1).split(".")); i += 1; continue
        m = re.match(r"^end(?:\s+(\S+))?\s*$", ln)
        if m and m.group(1) and stack and stack[-1] == m.group(1):
            n = len(stack.pop().split(".")); ns = ns[:-n] if n else ns; i += 1; continue
        m = DECL.match(re.sub(r"--.*$", "", ln))
        if m:
            kind, rest = m.group(1), m.group(2)
            kind = kind.split()[0] if kind.startswith("class") else kind
            if kind.startswith("class") : kind = "class"
            nm = NAME.match(rest)
            name = nm.group(1) if nm else None
            if kind == "instance" and (not name or rest.startswith(("(", "{", "[", "⦃", ":")) or not re.match(r"^[A-Za-z_]", name) or ":" in name):
                name = None
            if name is None and kind != "instance":
                name = None
            if name and name.startswith("_root_."):
                full = name[7:]
            elif name:
                full = ".".join(ns + [name])
            else:
                full = None
            dtext = cur_doc[0]
            own = None
            if dtext:
                mm = ANCH.match(re.sub(r"^/--\s*", "", dtext).strip())
                if mm: own = mm.group(1)
            if own: last_anchor = own
            out.append(dict(name=full, kind=kind, line=i + 1, own=own, anchor=own or last_anchor or section or title or "-", section=section))
            cur_doc[0] = None
        elif s and not s.startswith(("@[", "--")):
            cur_doc[0] = None
        i += 1
    return out, title, mathlib


cur_doc = [None]


def main():
    sections = []
    total = {"AreaLaw": 0, "AreaLawForMathlib": 0}
    names = []
    for lib in ("AreaLaw", "AreaLawForMathlib"):
        for p in sorted((ROOT / lib).rglob("*.lean")):
            rel = p.relative_to(ROOT).as_posix()
            cur_doc[0] = None
            ds, title, mathlib = decls(p, rel)
            total[lib] += len(ds)
            rows = []
            for d in ds:
                nm = d["name"] or f"(anonymous instance, line {d['line']})"
                if d["name"]: names.append(d["name"])
                extra = d["anchor"] if lib == "AreaLaw" else (mathlib or "no `Extends` line in the module docstring")
                rows.append(f"| `{nm}` | {rel}:{d['line']} | {d['kind']} | {extra.replace('|', '/')} |")
            hdr = "Anchor" if lib == "AreaLaw" else "Extends (Mathlib file)"
            sections.append(f"### `{rel}` ({len(ds)})\n\n| Declaration | File:line | Kind | {hdr} |\n|---|---|---|---|\n" + "\n".join(rows) + "\n")
    body = (f"{HEAD}\n\nEvery declaration of `AreaLaw/` ({total['AreaLaw']}) and `AreaLawForMathlib/` "
            f"({total['AreaLawForMathlib']}), grouped by file. Anchor = the `D*.n[.k]` in the declaration's own "
            "docstring, else that of the nearest preceding declaration with one in the same file, else the section "
            "heading. For `AreaLawForMathlib/` the last column is the Mathlib file the library file extends.\n\n"
            + "\n".join(sections))
    if "--write" in sys.argv:
        mp = ROOT / "Map.md"
        t = mp.read_text()
        k = t.find(HEAD)
        if k >= 0: t = t[:k].rstrip("\n") + "\n"
        mp.write_text(t.rstrip("\n") + "\n\n" + body)
        t = mp.read_text()
        miss = [n for n in names if n not in t.replace(body, "") and n not in body]
        print("declarations", total, "named", len(names), "missing from Map.md", len(miss))
    else:
        print(body)


main()
